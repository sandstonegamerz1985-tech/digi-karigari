"""AI listing assistant.

HOW IT WORKS
- analyze_listing() is the only function the rest of the app calls.
- It picks a "provider": a function that takes (image bytes, notes) and returns suggestions.
- "mock" (DEMO mode) uses simple keyword rules on the notes. It does NOT look at the image.
- "gemini" (LIVE mode) sends the image + notes to a Google Gemini vision model.
- "anthropic" (LIVE mode) sends the image + notes to a vision-capable Claude model.

TO ADD ANOTHER PROVIDER (for example OpenAI)
1. Write a function like _analyze_anthropic() that returns a dict with the same keys.
2. Add it to LIVE_PROVIDERS at the bottom and add its key to config.py / .env.
Nothing in the frontend needs to change.

The API key is read from the backend environment only. It is never sent to the browser.
"""
import base64
import json
import logging
import re

import httpx
from fastapi import HTTPException

from .config import settings
from .constants import CATEGORIES

log = logging.getLogger("digi_karigari.ai")


# ---------------------------------------------------------------------------
# Status (the frontend shows this so users always know which mode they are in)
# ---------------------------------------------------------------------------
def _live_config():
    """Returns (provider, model) if a real AI provider is selected AND has a key, else None."""
    if settings.AI_PROVIDER == "gemini" and settings.GEMINI_API_KEY:
        return "gemini", settings.GEMINI_MODEL
    if settings.AI_PROVIDER == "anthropic" and settings.ANTHROPIC_API_KEY:
        return "anthropic", settings.AI_MODEL
    return None


def is_live() -> bool:
    return _live_config() is not None


def ai_status() -> dict:
    live = _live_config()
    if live:
        provider, model = live
        names = {"gemini": "Google Gemini", "anthropic": "Anthropic Claude"}
        return {
            "mode": "live",
            "provider": provider,
            "model": model,
            "label": f"AI is connected ({names[provider]}). Suggestions are generated by a vision model - always review them.",
        }
    return {
        "mode": "demo",
        "provider": "mock",
        "model": None,
        "label": "DEMO MODE: no AI key is configured. Suggestions come from simple keyword rules on your notes; "
        "the photo is NOT analysed.",
    }


